import assert from 'node:assert/strict';
import { mkdtemp, rm } from 'node:fs/promises';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { pathToFileURL } from 'node:url';
import { build } from 'esbuild';

const folder = await mkdtemp(join(tmpdir(), 'vaultflow-persistence-'));
try {
  const outfile = join(folder, 'test.mjs');
  await build({ stdin: { contents: "export * from './src/lib/storage'; export * from './src/lib/asset-checkpoints'; export * from './src/lib/persistence'; export * from './src/lib/csv';", resolveDir: process.cwd() }, bundle: true, format: 'esm', platform: 'node', outfile });
  const f = await import(pathToFileURL(outfile));
  const mirror = new Map();
  globalThis.localStorage = { getItem: key => mirror.get(key) ?? null, setItem: (key, value) => mirror.set(key, value) };
  let writes = 0;
  globalThis.localStorage.setItem = (key, value) => { mirror.set(key, value); writes++; };
  globalThis.window = {};
  const settings = f.DEFAULT_SETTINGS;
  const account = { id: 'a', name: '测试银行', balance: 50000, type: 'cash', currency: 'CNY', createdAt: f.getToday(), updatedAt: f.getToday() };
  let data = { ...f.createEmptyAppData(), accounts: [account] };
  const checkpoint = f.createCheckpoint(data, [account], settings, '首次');
  data = f.fullSyncData({ ...data, assetCheckpoints: [checkpoint], transactions: [{ id: 't', date: f.getToday(), amount: 100, type: 'expense', accountId: 'a', category: '餐饮美食', source: 'csv', createdAt: f.getToday() }], forecastEvents: [{ id: 'f', name: '工资', amount: 1000, type: 'income', frequency: 'monthly', startDate: f.getToday(), enabled: true }] }, settings);
  data.accountBalanceHistory = [{ id: 'balance-1', accountId: 'a', date: f.getToday(), recordedAt: new Date().toISOString(), balance: 50000, currency: 'CNY', accountType: 'cash', note: '单账户节点', source: 'account-edit' }];
  await f.savePersistedData(data);
  const loaded = await f.loadPersistedData(f.createEmptyAppData());
  assert.equal(JSON.stringify(loaded.assetCheckpoints), JSON.stringify(data.assetCheckpoints));
  assert.deepEqual(loaded.forecastEvents, data.forecastEvents);
  assert.equal(loaded.transactions.length, 1);
  const backup = JSON.stringify(loaded);
  const restored = f.validateAppData(JSON.parse(backup));
  assert.equal(restored.success, true);
  assert.equal(JSON.stringify(restored.data.assetCheckpoints), JSON.stringify(data.assetCheckpoints));
  const merged = f.importDataJsonMerge(backup, loaded);
  assert.equal(merged.success, true);
  assert.equal(merged.data.transactions.length, 1, 'reimport is idempotent');
  assert.equal(merged.data.assetCheckpoints.length, 1);
  assert.equal(merged.data.forecastEvents.length, 1);
  assert.deepEqual(restored.data.accountBalanceHistory, data.accountBalanceHistory);
  assert.equal(merged.data.accountBalanceHistory.length, 1);
  const divergent = { ...loaded, assetCheckpoints: [{ ...checkpoint, note: '不同历史' }] };
  assert.equal(f.importDataJsonMerge(JSON.stringify(divergent), loaded).success, false);
  mirror.set('vaultflow_data', '{broken');
  const before = writes;
  await assert.rejects(f.loadPersistedData(f.createEmptyAppData()), /原数据已保留/);
  assert.equal(writes, before, 'corrupt browser data is never overwritten');
  mirror.set('vaultflow_data', '{}');
  await assert.rejects(f.loadPersistedData(f.createEmptyAppData()), /校验失败/);
  mirror.set('vaultflow_settings', '{broken');
  await assert.rejects(f.loadPersistedSettings(), /原数据已保留/);
  localStorage.setItem = () => { throw new Error('quota exceeded'); };
  await assert.rejects(f.savePersistedData(data), /quota exceeded/);
  assert.equal(mirror.get('vaultflow_data'), '{}', 'a failed write leaves the stored revision untouched');
  console.log('Persistence checks passed: browser save/reload, JSON restore, idempotent merge, divergent history rejection, corrupt-file protection, write failure propagation.');
} finally { await rm(folder, { recursive: true, force: true }); }
